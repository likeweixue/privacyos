#!/bin/bash
# ============================================================================
# PrivacyOS 可选组件补装脚本
#
# Debian 13.7 DVD-1 不包含 Samba 服务端 / NFS 服务端 / Docker，本脚本在系统
# 联网后自动从 deb.debian.org 安装这些组件，并完成基础配置。
#
# 可手动执行：
#   privacyos-provision            # 已完成后跳过
#   privacyos-provision --force    # 强制重新检查并补装
# ============================================================================
set -u

STATE_DIR="/var/lib/privacyos"
MARKER="${STATE_DIR}/provisioned"
LOG_TAG="privacyos-provision"
FORCE=0
[ "${1:-}" = "--force" ] && FORCE=1

log() { printf '[%s] %s\n' "$(date '+%F %T')" "$*"; }

if [ -f "${MARKER}" ] && [ "${FORCE}" -eq 0 ]; then
    log "可选组件已处理完成（${MARKER}），跳过"
    exit 0
fi

mkdir -p "${STATE_DIR}"

log "检查网络连通性…"
ONLINE=0
for host in deb.debian.org deb.debian.org; do
    if timeout 8 getent hosts "${host}" >/dev/null 2>&1; then
        ONLINE=1
        break
    fi
done
if [ "${ONLINE}" -ne 1 ]; then
    log "当前无法解析 deb.debian.org，跳过在线组件安装。"
    log "可稍后联网执行: privacyos-provision --force"
    exit 0
fi

log "配置在线软件源…"
install -d -m 0755 /etc/apt/sources.list.d
if [ -f /usr/share/keyrings/debian-archive-keyring.gpg ]; then
    cat > /etc/apt/sources.list.d/debian-online.sources <<'EOF'
Types: deb
URIs: http://deb.debian.org/debian
Suites: trixie trixie-updates
Components: main contrib non-free non-free-firmware
Signed-By: /usr/share/keyrings/debian-archive-keyring.gpg
EOF
else
    warn_keyring=1
    cat > /etc/apt/sources.list.d/debian-online.list <<'EOF'
deb http://deb.debian.org/debian trixie main contrib non-free non-free-firmware
deb http://deb.debian.org/debian trixie-updates main contrib non-free non-free-firmware
EOF
fi

log "更新软件索引…"
if ! timeout 300 apt-get update -o Acquire::Retries=3 -o Acquire::http::Timeout=20 >/dev/null 2>&1; then
    log "apt-get update 失败，稍后可重试"
    timeout 300 apt-get update -o Acquire::Retries=3 || true
fi

log "安装可选组件（Samba / NFS / Docker / 工具）…"
PACKAGES=(
    samba nfs-kernel-server
    docker.io docker-compose
    libimage-exiftool-perl
    nvme-cli iotop iftop quota quotatool attr sqlite3 zip
)
FAILED=()
for pkg in "${PACKAGES[@]}"; do
    if dpkg -s "${pkg}" >/dev/null 2>&1; then
        continue
    fi
    if ! timeout 600 apt-get install -y --no-install-recommends -o Dpkg::Options::=--force-confdef \
        -o Dpkg::Options::=--force-confold "${pkg}" >>/var/log/privacyos/provision.log 2>&1; then
        FAILED+=("${pkg}")
        log "  ! ${pkg} 安装失败（面板将自动降级该功能）"
    else
        log "  + ${pkg} 已安装"
    fi
done

# ---------------------------------------------------------------------------
# Samba：同步 padmin 的 SMB 密码并启动服务
# ---------------------------------------------------------------------------
if command -v smbpasswd >/dev/null 2>&1; then
    if [ -f /etc/privacyos/privacyos.env ]; then
        PW="$(sed -n 's/^PRIVACYOS_ADMIN_PASSWORD=//p' /etc/privacyos/privacyos.env | head -1)"
        if [ -n "${PW}" ] && ! pdbedit -L 2>/dev/null | grep -q '^padmin:'; then
            printf '%s\n%s\n' "${PW}" "${PW}" | smbpasswd -a -s padmin >/dev/null 2>&1 || true
            log "  + 已创建 padmin 的 Samba 账户"
        fi
    fi
    if command -v testparm >/dev/null 2>&1 && testparm -s >/dev/null 2>&1; then
        systemctl enable smbd nmbd >/dev/null 2>&1 || true
        systemctl restart smbd >/dev/null 2>&1 || systemctl start smbd >/dev/null 2>&1 || true
        systemctl restart nmbd >/dev/null 2>&1 || systemctl start nmbd >/dev/null 2>&1 || true
        log "  + Samba 服务已启动"
    else
        log "  ! smb.conf 校验未通过，Samba 未启动；请在面板「网络与共享」重新应用配置"
    fi
fi

# ---------------------------------------------------------------------------
# NFS：导出目录并启动服务
# ---------------------------------------------------------------------------
if command -v exportfs >/dev/null 2>&1; then
    if [ ! -s /etc/exports ]; then
        cat > /etc/exports <<'EOF'
# Generated by PrivacyOS
/data/users 192.168.0.0/16(rw,sync,no_subtree_check,root_squash,crossmnt)
/data/users 10.0.0.0/8(rw,sync,no_subtree_check,root_squash,crossmnt)
EOF
    fi
    systemctl enable nfs-kernel-server >/dev/null 2>&1 || true
    systemctl restart nfs-kernel-server >/dev/null 2>&1 || systemctl start nfs-kernel-server >/dev/null 2>&1 || true
    exportfs -ra >/dev/null 2>&1 || true
    log "  + NFS 服务已启动"
fi

# ---------------------------------------------------------------------------
# Docker
# ---------------------------------------------------------------------------
if command -v docker >/dev/null 2>&1; then
    systemctl enable docker >/dev/null 2>&1 || true
    systemctl restart docker >/dev/null 2>&1 || systemctl start docker >/dev/null 2>&1 || true
    if id padmin >/dev/null 2>&1; then
        usermod -aG docker padmin 2>/dev/null || true
    fi
    log "  + Docker 服务已启动"
fi

# ---------------------------------------------------------------------------
# 完成标记
# ---------------------------------------------------------------------------
{
    echo "provisioned_at=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "failed_packages=${FAILED[*]:-}"
} > "${MARKER}"

log "可选组件处理完成"
