// Interface is a network interface summary.
type Interface struct {
	Name      string   `json:"name"`
	MAC       string   `json:"mac"`
	State     string   `json:"state"`
	MTU       int      `json:"mtu"`
	Addresses []string `json:"addresses"`
	Mode      string   `json:"mode"`
	Gateway   string   `json:"gateway,omitempty"`
}

// Interfaces lists network interfaces.
func (s *Service) Interfaces(ctx context.Context) ([]Interface, error) {
	if s.Dev() {
		return []Interface{
			{Name: "eth0", MAC: "3c:7c:3f:12:34:56", State: "UP", MTU: 1500, Addresses: []string{"192.168.1.20/24"}, Mode: "static", Gateway: "192.168.1.1"},
			{Name: "wlan0", MAC: "a4:83:e7:ab:cd:ef", State: "DOWN", MTU: 1500, Addresses: []string{}, Mode: "dhcp"},
			{Name: "docker0", MAC: "02:42:8a:11:22:33", State: "UP", MTU: 1500, Addresses: []string{"172.17.0.1/16"}, Mode: "bridge"},
		}, nil
	}
	out, err := s.run(ctx, 10*time.Second, "ip", "-j", "addr", "show")
	if err != nil {
		return nil, fmt.Errorf("读取网卡失败: %w", err)
	}
	var raw []struct {
		IfName    string   `json:"ifname"`
		Address   string   `json:"address"`
		MTU       int      `json:"mtu"`
		OperState string   `json:"operstate"`
		Flags     []string `json:"flags"`
		AddrInfo  []struct {
			Family    string `json:"family"`
			Local     string `json:"local"`
			PrefixLen int    `json:"prefixlen"`
		} `json:"addr_info"`
	}
	if err := json.Unmarshal([]byte(out), &raw); err != nil {
		return nil, err
	}
	var result []Interface
	for _, r := range raw {
		iface := Interface{Name: r.IfName, MAC: r.Address, State: r.OperState, MTU: r.MTU, Mode: "dhcp"}
		up := false
		for _, f := range r.Flags {
			if f == "UP" {
				up = true
			}
			if f == "LOOPBACK" {
				iface.Mode = "loopback"
			}
		}
		if !up && iface.Mode != "loopback" {
			iface.State = "DOWN"
		}
		for _, a := range r.AddrInfo {
			if a.Family == "inet" {
				iface.Addresses = append(iface.Addresses, fmt.Sprintf("%s/%d", a.Local, a.PrefixLen))
			}
		}
		result = append(result, iface)
	}
	return result, nil
}

// ApplyInterface writes an ifupdown stanza and brings the interface up.
func (s *Service) ApplyInterface(ctx context.Context, name, mode, address, gateway, dns string) error {
	if !validIface(name) {
		return fmt.Errorf("非法网卡名")
	}
	if mode != "dhcp" && mode != "static" {
		return fmt.Errorf("模式必须是 dhcp 或 static")
	}
	if mode == "static" {
		if _, _, err := net.ParseCIDR(firstNonEmpty(address, "/")); err != nil {
			return fmt.Errorf("静态地址格式应为 192.168.1.10/24")
		}
		if gateway != "" && net.ParseIP(gateway) == nil {
			return fmt.Errorf("网关格式不正确")
		}
		for _, d := range strings.Fields(dns) {
			if net.ParseIP(d) == nil {
				return fmt.Errorf("DNS 格式不正确: %s", d)
			}
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Managed by PrivacyOS\nauto %s\niface %s inet %s\n", name, name, mode)
	if mode == "static" {
		fmt.Fprintf(&b, "    address %s\n", address)
		if gateway != "" {
			fmt.Fprintf(&b, "    gateway %s\n", gateway)
		}
	}
	if dns != "" {
		fmt.Fprintf(&b, "    dns-nameservers %s\n", strings.Join(strings.Fields(dns), " "))
	}
	if s.Dev() {
		dir := filepath.Join(s.Cfg.ConfigDir, "network")
		_ = os.MkdirAll(dir, 0o750)
		return os.WriteFile(filepath.Join(dir, name+".conf"), []byte(b.String()), 0o640)
	}
	path := filepath.Join("/etc/network/interfaces.d", "privacyos-"+name+".conf")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return err
	}
	if _, err := exec.LookPath("ifup"); err != nil {
		return fmt.Errorf("未找到 ifupdown，请手动应用网络配置")
	}
	ctx, cancel := context.WithTimeout(ctx, 60*time.Second)
	defer cancel()
	_, _ = exec.CommandContext(ctx, "ifdown", "--force", name).CombinedOutput()
	if out, err := exec.CommandContext(ctx, "ifup", name).CombinedOutput(); err != nil {
		return fmt.Errorf("应用网络配置失败: %v %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// SetDNS writes /etc/resolv.conf.
func (s *Service) SetDNS(ctx context.Context, servers []string) error {
	for _, srv := range servers {
		if net.ParseIP(srv) == nil {
			return fmt.Errorf("DNS 地址不合法: %s", srv)
		}
	}
	var b strings.Builder
	b.WriteString("# Generated by PrivacyOS\n")
	for _, srv := range servers {
		fmt.Fprintf(&b, "nameserver %s\n", srv)
	}
	b.WriteString("options edns0 trust-ad\n")
	path := "/etc/resolv.conf"
	if s.Dev() {
		path = filepath.Join(s.Cfg.ConfigDir, "resolv.conf")
	}
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return err
	}
	return nil
}

// Port is a listening socket.
type Port struct {
	Protocol string `json:"protocol"`
	Address  string `json:"address"`
	Port     int    `json:"port"`
	Process  string `json:"process"`
	PID      int    `json:"pid,omitempty"`
}

// Ports lists listening TCP/UDP sockets.
func (s *Service) Ports(ctx context.Context) ([]Port, error) {
	if s.Dev() {
		return []Port{
			{Protocol: "tcp", Address: "0.0.0.0", Port: 22, Process: "sshd", PID: 812},
			{Protocol: "tcp", Address: "0.0.0.0", Port: 80, Process: "privacyos-server", PID: 1234},
			{Protocol: "tcp", Address: "0.0.0.0", Port: 443, Process: "privacyos-server", PID: 1234},
			{Protocol: "tcp", Address: "0.0.0.0", Port: 445, Process: "smbd", PID: 1543},
			{Protocol: "tcp", Address: "0.0.0.0", Port: 2049, Process: "nfsd", PID: 902},
			{Protocol: "tcp", Address: "0.0.0.0", Port: 8096, Process: "docker-proxy", PID: 2201},
			{Protocol: "udp", Address: "0.0.0.0", Port: 53, Process: "adguardhome", PID: 3301},
		}, nil
	}
	out, err := s.run(ctx, 10*time.Second, "ss", "-tulpnH")
	if err != nil {
		return nil, err
	}
	reProc := regexp.MustCompile(`users:\(\("([^"]+)",pid=(\d+)`)
	var ports []Port
	for _, line := range strings.Split(out, "\n") {
		fields := strings.Fields(line)
		if len(fields) < 5 {
			continue
		}
		proto := fields[0]
		if proto != "tcp" && proto != "udp" {
			continue
		}
		local := fields[4]
		idx := strings.LastIndex(local, ":")
		if idx < 0 {
			continue
		}
		addr := local[:idx]
		portNum, _ := strconv.Atoi(local[idx+1:])
		item := Port{Protocol: proto, Address: strings.Trim(addr, "[]"), Port: portNum}
		if m := reProc.FindStringSubmatch(line); m != nil {
			item.Process = m[1]
			item.PID, _ = strconv.Atoi(m[2])
		}
		ports = append(ports, item)
	}
	return ports, nil
}

// FirewallStatus returns the current PrivacyOS nftables table.
func (s *Service) FirewallStatus(ctx context.Context) string {
	if s.Dev() {
		data, err := os.ReadFile(filepath.Join(s.Cfg.ConfigDir, "firewall", "privacyos.nft"))
		if err != nil {
			return ""
		}
		return string(data)
	}
	out, err := s.run(ctx, 10*time.Second, "nft", "list", "table", "inet", "privacyos")
	if err != nil {
		return ""
	}
	return out
}

// RenderFirewall builds the default nftables ruleset.
func (s *Service) RenderFirewall(extraPorts []int) string {
	base := map[int]bool{22: true, 80: true, 443: true, 445: true, 2049: true, 3000: true, 8080: true}
	for _, p := range extraPorts {
		if p > 0 && p < 65536 {
			base[p] = true
		}
	}
	var nums []string
	for p := range base {
		nums = append(nums, strconv.Itoa(p))
	}
	// Stable order.
	for i := 0; i < len(nums); i++ {
		for j := i + 1; j < len(nums); j++ {
			if nums[j] < nums[i] {
				nums[i], nums[j] = nums[j], nums[i]
			}
		}
	}
	portSet := strings.Join(nums, ", ")
	return fmt.Sprintf(`table inet privacyos {
  chain input {
    type filter hook input priority 0; policy drop;
    ct state established,related accept
    ct state invalid drop
    iif "lo" accept
    ip protocol icmp accept
    ip6 nexthdr ipv6-icmp accept
    tcp dport { %s } accept
    udp dport { %s } accept
    log prefix "privacyos-drop: " limit rate 5/minute
  }
  chain forward {
    type filter hook forward priority 0; policy accept;
  }
  chain output {
    type filter hook output priority 0; policy accept;
  }
}
`, portSet, portSet)
}

// ApplyFirewall installs the ruleset with an automatic 120s rollback unless
// confirmed through ConfirmFirewall.
func (s *Service) ApplyFirewall(ctx context.Context, ruleset string) error {
	if strings.Contains(ruleset, "policy accept;") && strings.Count(ruleset, "policy drop;") == 0 {
		return fmt.Errorf("规则集不安全：input 链必须包含 policy drop")
	}
	if s.Dev() {
		dir := filepath.Join(s.Cfg.ConfigDir, "firewall")
		_ = os.MkdirAll(dir, 0o750)
		return os.WriteFile(filepath.Join(dir, "privacyos.nft"), []byte(ruleset), 0o640)
	}
	if _, err := exec.LookPath("nft"); err != nil {
		return fmt.Errorf("未安装 nftables")
	}
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "nft", "-f", "-")
	cmd.Stdin = strings.NewReader(ruleset)
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("应用防火墙失败: %v %s", err, strings.TrimSpace(string(out)))
	}
	rollback := exec.CommandContext(ctx, "systemd-run", "--on-active=120", "--unit=privacyos-fw-rollback",
		"/usr/sbin/nft", "delete", "table", "inet", "privacyos")
	_ = rollback.Run()
	return nil
}

// ConfirmFirewall cancels the automatic rollback timer.
func (s *Service) ConfirmFirewall(ctx context.Context) error {
	if s.Dev() {
		return nil
	}
	ctx, cancel := context.WithTimeout(ctx, 20*time.Second)
	defer cancel()
	_ = exec.CommandContext(ctx, "systemctl", "stop", "privacyos-fw-rollback.timer").Run()
	_ = exec.CommandContext(ctx, "systemctl", "reset-failed", "privacyos-fw-rollback.timer").Run()
	return nil
}

