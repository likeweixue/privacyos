// PublicIP discovers the current public address.
func (s *Service) PublicIP(ctx context.Context) (string, error) {
	for _, endpoint := range []string{"https://api.ipify.org", "https://ifconfig.me/ip", "https://ipv4.icanhazip.com"} {
		req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
		if err != nil {
			continue
		}
		resp, err := (&http.Client{Timeout: 8 * time.Second}).Do(req)
		if err != nil {
			continue
		}
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 64))
		resp.Body.Close()
		ip := strings.TrimSpace(string(body))
		if net.ParseIP(ip) != nil {
			return ip, nil
		}
	}
	return "", fmt.Errorf("无法获取公网 IP")
}

// UpdateDDNS updates the configured dynamic DNS provider.
func (s *Service) UpdateDDNS(ctx context.Context, provider, domain, token, username, password, customURL string) (string, error) {
	if s.Dev() {
		return "203.0.113.42", nil
	}
	ip, err := s.PublicIP(ctx)
	if err != nil {
		return "", err
	}
	client := &http.Client{Timeout: 15 * time.Second}
	switch strings.ToLower(provider) {
	case "duckdns":
		u := fmt.Sprintf("https://www.duckdns.org/update?domains=%s&token=%s&ip=%s",
			url.QueryEscape(domain), url.QueryEscape(token), url.QueryEscape(ip))
		if err := getExpect(ctx, client, u, "OK"); err != nil {
			return ip, err
		}
	case "cloudflare":
		if err := s.updateCloudflare(ctx, client, domain, token, ip); err != nil {
			return ip, err
		}
	case "custom":
		if customURL == "" {
			return ip, fmt.Errorf("自定义 DDNS 需要填写 URL 模板")
		}
		u := strings.ReplaceAll(customURL, "{ip}", url.QueryEscape(ip))
		u = strings.ReplaceAll(u, "{domain}", url.QueryEscape(domain))
		if username != "" {
			u = strings.ReplaceAll(u, "{username}", url.QueryEscape(username))
			u = strings.ReplaceAll(u, "{password}", url.QueryEscape(password))
		}
		if err := getExpect(ctx, client, u, ""); err != nil {
			return ip, err
		}
	default:
		return ip, fmt.Errorf("不支持的 DDNS 服务商 %q", provider)
	}
	return ip, nil
}

func (s *Service) updateCloudflare(ctx context.Context, client *http.Client, domain, token, ip string) error {
	if token == "" {
		return fmt.Errorf("Cloudflare 需要 API Token")
	}
	parts := strings.Split(domain, ".")
	if len(parts) < 2 {
		return fmt.Errorf("域名格式不正确")
	}
	zoneName := strings.Join(parts[len(parts)-2:], ".")
	api := "https://api.cloudflare.com/client/v4"
	doReq := func(method, reqURL string, body []byte) ([]byte, error) {
		req, err := http.NewRequestWithContext(ctx, method, reqURL, bytes.NewReader(body))
		if err != nil {
			return nil, err
		}
		req.Header.Set("Authorization", "Bearer "+token)
		req.Header.Set("Content-Type", "application/json")
		resp, err := client.Do(req)
		if err != nil {
			return nil, err
		}
		defer resp.Body.Close()
		data, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
		if resp.StatusCode >= 300 {
			return data, fmt.Errorf("Cloudflare API %d: %s", resp.StatusCode, strings.TrimSpace(string(data)))
		}
		return data, nil
	}
	zoneBody, err := doReq(http.MethodGet, api+"/zones?name="+url.QueryEscape(zoneName), nil)
	if err != nil {
		return err
	}
	var zone struct {
		Result []struct {
			ID string `json:"id"`
		} `json:"result"`
	}
	if err := json.Unmarshal(zoneBody, &zone); err != nil || len(zone.Result) == 0 {
		return fmt.Errorf("未找到 Cloudflare 区域 %s", zoneName)
	}
	zoneID := zone.Result[0].ID
	recBody, err := doReq(http.MethodGet, fmt.Sprintf("%s/zones/%s/dns_records?name=%s", api, zoneID, url.QueryEscape(domain)), nil)
	if err != nil {
		return err
	}
	var rec struct {
		Result []struct {
			ID string `json:"id"`
		} `json:"result"`
	}
	if err := json.Unmarshal(recBody, &rec); err != nil {
		return err
	}
	payload, _ := json.Marshal(map[string]any{
		"type": "A", "name": domain, "content": ip, "ttl": 120, "proxied": false,
	})
	if len(rec.Result) > 0 {
		_, err = doReq(http.MethodPut, fmt.Sprintf("%s/zones/%s/dns_records/%s", api, zoneID, rec.Result[0].ID), payload)
		return err
	}
	_, err = doReq(http.MethodPost, fmt.Sprintf("%s/zones/%s/dns_records", api, zoneID), payload)
	return err
}

func getExpect(ctx context.Context, client *http.Client, endpoint, expect string) error {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, endpoint, nil)
	if err != nil {
		return err
	}
	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	body, _ := io.ReadAll(io.LimitReader(resp.Body, 4096))
	text := strings.TrimSpace(string(body))
	if resp.StatusCode >= 300 {
		return fmt.Errorf("DDNS HTTP %d: %s", resp.StatusCode, text)
	}
	if expect != "" && text != "" && !strings.Contains(text, expect) {
		return fmt.Errorf("DDNS 返回异常: %s", text)
	}
	return nil
}

func validIface(name string) bool {
	if name == "" || len(name) > 15 {
		return false
	}
	for _, r := range name {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '.' || r == '-' || r == '_') {
			return false
		}
	}
	return true
}
